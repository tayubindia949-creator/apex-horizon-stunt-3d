export function getUpgradeCost(currentLevel: number): number {
  return currentLevel * 220;
}

export function getEffectiveCarStats(car: CarSpec, upgrades: { engine: number; nitro: number; suspension: number }) {
  const topSpeedKmh = Math.round(car.baseSpeed + (upgrades.engine - 1) * 11);
  const accel = car.baseAccel + (upgrades.engine - 1) * 2.8;
  const handling = car.baseHandling + (upgrades.suspension - 1) * 0.08;
  const nitroPower = car.baseNitroPower + (upgrades.nitro - 1) * 0.06;
  const nitroDurationSec = 3.2 + (upgrades.nitro - 1) * 0.65;
  return { topSpeedKmh, accel, handling, nitroPower, nitroDurationSec };
}

